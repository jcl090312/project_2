    if user_choice != "선택하세요":
        if user_choice == q_dict['a']:
            st.success("정답입니다! 🎉")
        else:
            st.error(f"오답입니다. 정답은 **{q_dict['a']}** 입니다. 🥲")
            
    st.markdown("<br>", unsafe_allow_html=True) # 문제 사이의 간격 띄우기
