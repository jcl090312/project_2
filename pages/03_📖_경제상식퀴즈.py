    st.markdown(f"**Q{i}. {q_dict['q']}**")
    
    # 선택지 앞에 '선택하세요'를 추가하여 기본 선택값을 빈값으로 만듦
    options = ["선택하세요"] + q_dict['options']
    
    # 사용자의 선택 저장 (고유 키(key)를 지정해야 각 문제가 독립적으로 동작함)
